-- Run in Supabase SQL Editor. All tables are server-only; no anon/authenticated access.
create table if not exists public.store_settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);
create table if not exists public.store_products (
  id bigint generated by default as identity primary key,
  provider text not null default 'accszone',
  provider_listing_id bigint not null,
  slug text not null,
  title text not null,
  category text not null default 'Facebook',
  description text not null default '',
  supplier_price_cents int not null check (supplier_price_cents >= 0),
  stock int not null default 0 check(stock >= 0),
  published boolean not null default false,
  last_synced_at timestamptz not null default now(),
  unique(provider, provider_listing_id)
);
create index if not exists store_products_visible on public.store_products (published, stock);
create table if not exists public.store_orders (
  id uuid primary key,
  lookup_hash text not null unique,
  customer_email text not null,
  product_id bigint not null references public.store_products(id),
  product_title text not null,
  quantity int not null check(quantity between 1 and 20),
  unit_price_cents int not null check(unit_price_cents >= 0),
  supplier_unit_price_cents int not null check(supplier_unit_price_cents >= 0),
  total_cents int not null check(total_cents >= 0),
  pay_network text not null default 'TRC20',
  pay_wallet text not null,
  payment_tx_hash text unique,
  ip_hash text,
  status text not null default 'awaiting_payment' check(status in ('awaiting_payment', 'fulfilling', 'fulfilled', 'needs_review', 'cancelled')),
  supplier_order_id text,
  delivery_ciphertext text,
  error_message text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists store_orders_ip on public.store_orders (ip_hash, created_at desc);
create index if not exists store_orders_date on public.store_orders (created_at desc);
create index if not exists store_orders_status on public.store_orders (status);

alter table public.store_settings enable row level security;
alter table public.store_products enable row level security;
alter table public.store_orders enable row level security;
-- No RLS policies: only the server-side service role may access them.

insert into public.store_settings(key,value) values
