-- Bulk supplier sync deliberately never flips published=true/false.
create or replace function public.store_sync_products(payload jsonb)
returns int language plpgsql security invoker as $$
declare n int;
begin
  insert into public.store_products
    (provider, provider_listing_id, slug, title, category, description, supplier_price_cents, stock, last_synced_at)
  select provider, provider_listing_id, slug, title, category, description, supplier_price_cents, stock, now()
  from jsonb_to_recordset(payload) as x(
    provider text, provider_listing_id bigint, slug text, title text, category text,
    description text, supplier_price_cents int, stock int, last_synced_at timestamptz
  )
  on conflict (provider,provider_listing_id) do update set
    slug=excluded.slug, title=excluded.title, category=excluded.category,
    description=excluded.description, supplier_price_cents=excluded.supplier_price_cents,
    stock=excluded.stock, last_synced_at=now();
  get diagnostics n = row_count;
  return n;
end $$;
revoke all on function public.store_sync_products(jsonb) from public, anon, authenticated;
grant execute on function public.store_sync_products(jsonb) to service_role;
